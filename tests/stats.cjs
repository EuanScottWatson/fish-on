const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const Module=require('node:module');
const babel=require('@babel/core');
const file=path.join(__dirname,'..','stats.js');
const code=babel.transformSync(fs.readFileSync(file,'utf8'),{filename:file,configFile:false,babelrc:false,plugins:['@babel/plugin-transform-modules-commonjs']}).code;
const mod=new Module(file,module);mod.filename=file;mod.paths=module.paths;mod._compile(code,file);
const {fishingSummary}=mod.exports;
const catches=[{species:'Pike',place:'River Test',date:'2026-05-17'},{species:' pike ',place:' river test ',date:'2025-01-01'},{species:'Carp',place:'Lake',date:''},{species:'Trout',date:'2026-02-30'}];
const offline=fishingSummary(catches,null,2026);
assert.equal(offline.catches,4);assert.equal(offline.species,3);assert.equal(offline.caughtThisYear,1);assert.equal(offline.trips,null);
assert.deepEqual(offline.years,[{label:'2026',count:1},{label:'2025',count:1}]);
assert.equal(offline.months[0],1);assert.equal(offline.months[4],1);assert.equal(offline.months[1],0);
assert.deepEqual(offline.topSpecies[0],{label:'Pike',count:2});assert.deepEqual(offline.topPlaces[0],{label:'River Test',count:2});assert.equal(offline.undatedCatches,2);
const online=fishingSummary(catches,[{catch_ids:['one']},{catch_ids:[]}],2026);
assert.equal(online.trips,2);assert.equal(online.tripsWithLinkedCatches,1);
const empty=fishingSummary([],[],2026);assert.equal(empty.catches,0);assert.equal(empty.trips,0);assert.deepEqual(empty.years,[]);
assert.equal(fishingSummary([{date:'2024-02-29'},{date:'2025-02-29'},{date:'2026-13-01'}],[],2024).undatedCatches,2);
